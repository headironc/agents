// Bundles each deployed executable into one self-contained file under delivery/tools/.
//
// The installer copies tracked source without runtime dependencies. A tool that imports a package
// would therefore resolve nothing once deployed, so the product that ships is a standalone bundle.
// The reviewed material stays the entry source; this file and the freshness test prove the product
// derives from it.
//
// Usage: node scripts/bundle-tools.ts [--check]
//
// - Read [build tool contract](check.ts). Use tool `bun`.

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

export const bundledTools = [
  {
    source: "scripts/task-temp.ts",
    product: "delivery/tools/task-temp.mjs",
  },
  {
    source: "scripts/check-prose.mjs",
    product: "delivery/tools/check-prose.mjs",
  },
  {
    source: "scripts/check-ids.mjs",
    product: "delivery/tools/check-ids.mjs",
  },
] as const;

const SHEBANG = "#!/usr/bin/env node\n";

/** Builds one tool and returns the bytes that belong in the working tree. */
export function renderTool(
  root: string,
  tool: { source: string; product: string },
): string {
  const bun = path.join(root, ".cache/agents-tools/bin/bun");
  // A different bundler version produces different bytes, which would surface as an unexplained
  // freshness mismatch. Name the cause here instead.
  const manifest = JSON.parse(
    readFileSync(path.join(root, "package.json"), "utf8"),
  );
  const version = spawnSync(bun, ["--version"], {
    encoding: "utf8",
    timeout: 10_000,
  });
  if (
    version.status !== 0 ||
    version.stdout.trim() !== manifest.packageManager.slice(4)
  )
    throw new Error("Pinned Bun required");
  // Without this the bundler keeps the `development` export condition, which Node has no notion of,
  // so the product would be built from entries the reviewed source never loads: debug tracing and
  // live assertions in the shipped file, absent from the one under review.
  const result = spawnSync(
    bun,
    ["build", tool.source, "--target=node", "--production", "--minify"],
    {
      cwd: root,
      encoding: "utf8",
      timeout: 120_000,
      maxBuffer: 16 * 1024 * 1024,
    },
  );
  if (result.error) throw result.error;
  if (result.status !== 0)
    throw new Error(`Bundling ${tool.source} failed: ${result.stderr.trim()}`);
  const bundle = result.stdout;
  if (!bundle.startsWith(SHEBANG))
    throw new Error(`Bundled ${tool.source} lost its interpreter line`);
  const digest = createHash("sha256")
    .update(readFileSync(path.join(root, tool.source)))
    .digest("hex");
  const header = [
    "// Generated by scripts/bundle-tools.ts. Do not edit.",
    `// source=${tool.source}`,
    `// source_sha256=${digest}`,
  ].join("\n");
  return `${SHEBANG}${header}\n${bundle.slice(SHEBANG.length)}`;
}

export function renderTools(
  root: string,
): { product: string; content: string }[] {
  return bundledTools.map((tool) => ({
    product: tool.product,
    content: renderTool(root, tool),
  }));
}

if (
  path.resolve(process.argv[1] ?? "") === path.resolve(import.meta.filename)
) {
  const root = path.resolve(import.meta.dirname, "..");
  const check = process.argv.includes("--check");
  const stale: string[] = [];
  for (const { product, content } of renderTools(root)) {
    const file = path.join(root, product);
    let current: string | null = null;
    try {
      current = readFileSync(file, "utf8");
    } catch {
      current = null;
    }
    if (current === content) continue;
    if (check) {
      stale.push(product);
      continue;
    }
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, content, { mode: 0o644 });
    process.stdout.write(`bundle-tools: wrote ${product}\n`);
  }
  if (stale.length) {
    process.stderr.write(
      `bundle-tools: stale, rebuild with 'node scripts/bundle-tools.ts': ${stale.join(", ")}\n`,
    );
    process.exit(1);
  }
  if (!check) process.stdout.write("bundle-tools: up to date\n");
}
