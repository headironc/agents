import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { fromMarkdown } from "mdast-util-from-markdown";
import type { Root, RootContent } from "mdast";

export const generatedInstructionPaths: readonly string[] = [
  "delivery/AGENTS.md",
  "delivery/products/dsh/AGENTS.md",
  "delivery/products/antigravity/AGENTS.md",
];

const products = ["codex", "dsh", "antigravity"] as const;
type Product = (typeof products)[number];
const policyFiles = new Set([
  "common.md",
  "execution.md",
  "review.md",
  "tool-contracts.md",
  "rust.md",
  "sql.md",
  "writing.md",
  "models.md",
  "deepseek-harness.md",
]);

/** Validate with the existing Markdown parser; adapt only controlled inline links. */
export function renderInstructions(
  common: string,
  adapter: string,
  product: Product,
): string {
  const prefix = product === "antigravity" ? "config/" : "";
  const rewrite = (source: string): string => {
    let result = source;
    function visit(node: Root | RootContent): void {
      if ("url" in node) {
        const target = node.url;
        if (/^(?:https?:\/\/|#)/.test(target)) return;
        let mapped: string | undefined;
        for (const file of policyFiles) {
          for (const declared of [file, `../policy/${file}`]) {
            if (target === declared || target.startsWith(`${declared}#`))
              mapped = `policy/${target.slice(declared.length - file.length)}`;
          }
        }
        if (target.startsWith("../skills/") || target.startsWith("../tools/"))
          mapped = target.slice(3);
        if (
          !mapped ||
          mapped.split("/").some((part) => part === ".." || part === ".")
        )
          throw new Error(`Unsupported instruction link: ${target}`);
        // Source files deliberately use this one inline spelling. Reference links,
        // titles, escaping and alternate Markdown forms require an explicit design.
        if (node.type !== "link" || !source.includes(`](${target})`))
          throw new Error(`Unsupported instruction link syntax: ${target}`);
        result = result.replaceAll(`](${target})`, `](${prefix}${mapped})`);
      }
      if ("children" in node) for (const child of node.children) visit(child);
    }
    visit(fromMarkdown(source));
    return result;
  };
  const title = {
    codex: "Codex",
    dsh: "DeepSeek Harness",
    antigravity: "Antigravity",
  }[product];
  if (!common.startsWith("# Shared instructions\n"))
    throw new Error("Missing shared instruction title");
  return `<!-- Generated by scripts/build-instructions.ts. Do not edit. -->\n<!-- Sources: delivery/policy/common.md and delivery/rules/${product}.md -->\n\n# ${title} Instructions\n\n${rewrite(common.slice("# Shared instructions\n".length)).trim()}\n\n${rewrite(adapter).trim().replace(/^# /, "## ")}\n`;
}

export function buildInstructions(root: string, check = false): void {
  const common = readFileSync(
    path.join(root, "delivery/policy/common.md"),
    "utf8",
  );
  // Render every product before writing any output so invalid sources fail atomically.
  const outputs = products.map((product, index) => ({
    file: path.join(root, generatedInstructionPaths[index]!),
    text: renderInstructions(
      common,
      readFileSync(path.join(root, `delivery/rules/${product}.md`), "utf8"),
      product,
    ),
  }));
  for (const output of outputs) {
    if (check) {
      let actual: string;
      try {
        actual = readFileSync(output.file, "utf8");
      } catch {
        throw new Error(
          `Missing generated instructions: ${path.relative(root, output.file)}`,
        );
      }
      if (actual !== output.text)
        throw new Error(
          `Stale generated instructions: ${path.relative(root, output.file)}`,
        );
    } else {
      mkdirSync(path.dirname(output.file), { recursive: true });
      writeFileSync(output.file, output.text);
    }
  }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check"))
    throw new Error("Usage: build-instructions.ts [--check]");
  buildInstructions(
    path.resolve(import.meta.dirname, ".."),
    args[0] === "--check",
  );
  console.log(
    args[0] === "--check"
      ? "Generated instructions are current."
      : "Generated instructions for 3 products.",
  );
}
