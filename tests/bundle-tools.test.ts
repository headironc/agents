import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import {
  copyFileSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import os from "node:os";
import { isBuiltin } from "node:module";
import path from "node:path";
import test from "node:test";
import { bundledTools, renderTools } from "../scripts/bundle-tools.ts";

const root = path.resolve(import.meta.dirname, "..");

function temporary(t: { after: (fn: () => void) => void }): string {
  const directory = mkdtempSync(path.join(os.tmpdir(), "agents bundle "));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  return directory;
}

test("every committed product is the current render of its source", () => {
  for (const { product, content } of renderTools(root)) {
    assert.equal(
      readFileSync(path.join(root, product), "utf8"),
      content,
      `${product} is stale; rebuild with 'node scripts/bundle-tools.ts'`,
    );
  }
});

test("a product carries its provenance and no runtime dependency", () => {
  for (const tool of bundledTools) {
    const content = readFileSync(path.join(root, tool.product), "utf8");
    const [interpreter, marker, source] = content.split("\n");
    assert.equal(interpreter, "#!/usr/bin/env node");
    assert.equal(
      marker,
      "// Generated by scripts/bundle-tools.ts. Do not edit.",
    );
    assert.equal(source, `// source=${tool.source}`);
    // A deployed symlink resolves imports beside the snapshot, which carries no installed packages,
    // so anything the bundler left unresolved would only fail once deployed. The bundler rewrites a
    // CommonJS require through a local alias, so its call sites count as much as a literal one.
    // Two shapes, because a pattern that only knows one of them reports an empty list for the wrong
    // reason. A dynamic import and a require put the specifier straight after the keyword; a static
    // import puts it after `from`, and that is the shape the bundler actually emits.
    const specifiers = [
      ...content.matchAll(
        /(?:^|[^\w$.])(?:import|require)\s*\(?\s*["']([^"']+)["']/g,
      ),
      ...content.matchAll(
        /(?:^|[^\w$.])(?:import|export)\b[^;'"]*?from\s*["']([^"']+)["']/g,
      ),
    ].map((match) => match[1]!);
    // The products ship two builtins by this second shape, so an empty `bare` below is the result of
    // looking rather than of matching nothing at all.
    assert.ok(
      specifiers.length > 0,
      `${tool.product} yielded no specifiers, so the scan saw nothing`,
    );
    for (const [, alias] of content.matchAll(
      /(?:var|let|const)\s+([\w$]+)\s*=\s*(?:[\w$]+\.)?createRequire\s*\(/g,
    )) {
      const calls = new RegExp(
        `(?:^|[^\\w$.])${alias}\\s*\\(\\s*["']([^"']+)["']`,
        "g",
      );
      specifiers.push(
        ...[...content.matchAll(calls)].map((match) => match[1]!),
      );
    }
    const bare = specifiers.filter(
      (name) =>
        !name.startsWith("node:") && !name.startsWith(".") && !isBuiltin(name),
    );
    assert.deepEqual(
      [...new Set(bare)],
      [],
      `${tool.product} still resolves packages at runtime`,
    );
  }
});

test("a product is built from the entries the source loads, not the development ones", () => {
  // The bundler keeps the `development` export condition unless told otherwise, and Node has no
  // such condition. Taking it would ship debug tracing and live assertions that the reviewed source
  // never loads, so the product would not be the program that was reviewed.
  //
  // Each marker has to survive minification, which renames every module-scope binding and strips
  // the per-module comments. A function name or a path would be gone before this test could look
  // for it, leaving a list that reads like three guards and is one; these are all string literals.
  for (const tool of bundledTools) {
    const content = readFileSync(path.join(root, tool.product), "utf8");
    for (const marker of ["process.env.DEBUG", "Assertion", '"micromark"']) {
      assert.ok(
        !content.includes(marker),
        `${tool.product} carries the development entry: ${marker}`,
      );
    }
  }
});

// Each sample must make its tool speak, so that agreement is evidence rather than shared silence.
// Both current checkers speak by finding something and exiting 1. The status stays part of each
// sample rather than a constant here, so a tool that signals otherwise can join without a rewrite.
const samples: Record<
  string,
  {
    args: (directory: string) => string[];
    status: number;
    prepare?: (directory: string) => void;
  }
> = {
  "scripts/check-prose.mjs": {
    args: () => ["sample.md"],
    status: 1,
    prepare: (directory) =>
      writeFileSync(
        path.join(directory, "sample.md"),
        `${"字".repeat(45)}。\n\n这里缺空格Node贴着。\n`,
      ),
  },
  "scripts/check-ids.mjs": {
    args: () => ["sample.md"],
    status: 1,
    prepare: (directory) =>
      writeFileSync(
        path.join(directory, "sample.md"),
        "| ID | 说明 |\n| --- | --- |\n| A-05 | 五 |\n| A-02 | 二 |\n",
      ),
  },
};

test("a product runs outside the repository and agrees with its source", (t) => {
  const directory = temporary(t);
  for (const tool of bundledTools) {
    const sample = samples[tool.source];
    assert.ok(sample, `${tool.source} has no sample to run`);
    sample.prepare?.(directory);
    const run = (script: string) => {
      const result = spawnSync(
        process.execPath,
        [script, ...sample.args(directory)],
        { cwd: directory, encoding: "utf8", timeout: 60_000 },
      );
      assert.ifError(result.error);
      return { status: result.status, stdout: result.stdout };
    };
    // Copying it out of the tree removes every installed package from the resolution path.
    const deployed = path.join(directory, path.basename(tool.product));
    copyFileSync(path.join(root, tool.product), deployed);
    const product = run(deployed);
    assert.ok(
      product.stdout.trim(),
      `${tool.product} said nothing on its sample`,
    );
    assert.equal(
      product.status,
      sample.status,
      `${tool.product} did not reach its sample's outcome`,
    );
    const source = run(path.join(root, tool.source));
    assert.equal(
      product.stdout,
      source.stdout,
      `${tool.product} disagrees with ${tool.source}`,
    );
    // A gate reads the status, not the text, so agreement has to cover it. Today a usage error
    // writes nothing to stdout, which masks most divergences here; this states the property.
    assert.equal(
      product.status,
      source.status,
      `${tool.product} exits differently from ${tool.source}`,
    );
  }
});
